def format_package_caption(service: str, bundle: str) -> str:
    """Short text for the photo caption (Telegram limits captions to 1024 chars)."""
    data = PACKAGES[service][bundle]
    return f"<b>{data['title']}</b>\n<i>{data['subtitle']}</i>"


def format_package_details(service: str, bundle: str) -> str:
    """Full package description sent as a separate text message."""
    data = PACKAGES[service][bundle]
    features = "\n".join(f"• {f}" for f in data["features"])
    return (
        f"<b>Что входит в пакет:</b>\n{features}\n\n"
        f"<b>Что получает клиент:</b> {data['gets']}"
    )
